/**
 * Dumps the HTML content-model schema as EDN defs for the Clojure port's
 * call-driven WellFormer. Everything is derived through the module's
 * public API so the dump cannot drift from the source tables.
 * Regenerate: node tools/dump-schema-clj.mjs (paste into
 * implementations/clojure/src/texy/wellformer.clj, driver section).
 */
import * as Schema from '../src/Output/Html/Schema.js';

const kw = s => ':' + s;
const set = m => `#{:${[...m.keys()].join(' :')}}`;
const known = [...new Set([...Object.keys(Schema.defaultAllowedTags), 'html', 'head', 'body', 'style'])].filter(t => t !== '*').sort();
const EMPTY = new Map();
// a sentinel parent: a transparent model passes it through, a fixed one ignores it
const PARENT = new Map([['%%PARENT%%', 1]]);
const phrasing = Schema.phrasingContent;
const flow = Schema.flowContent;

const rows = [];
for (const tag of known) {
	const c = Schema.childContent(tag, PARENT);
	const additions = Schema.childContent(tag, EMPTY);
	const inline = Schema.inlineElements.has(tag);
	const replaced = Schema.inlineElements.get(tag) === 1;
	const isVoid = Schema.voidElements.has(tag);
	const optionalEnd = Schema.hasOptionalEnd(tag);
	const kids = (xs, sep) => (xs.length ? [sep, ...xs.map(kw).join(' ').split(' ')].join(' ') : '');
	const kidsVec = xs => (xs.length ? `[${xs.map(kw).join(' ')}]` : '[]');
	let content;
	if (c.has('%%PARENT%%')) {
		content = `[:transparent ${kidsVec([...additions.keys()])}]`;
	} else if (additions === phrasing) {
		content = '[:phrasing-default]';
	} else if (additions === flow) {
		content = '[:flow-default]';
	} else {
		content = `[:explicit ${kidsVec([...additions.keys()])}]`;
	}
	rows.push(`\t"${tag}" {:inline ${inline ? (replaced ? ':replaced' : ':inline') : ':block'} :void ${isVoid} :optional-end ${optionalEnd} :content ${content}}`);
}

console.log(';; GENERATED by implementations/node.js/tools/dump-schema-clj.mjs - do not edit by hand.');
console.log(';; :content - [:phrasing-default] category default is the phrasing-content set;');
console.log(';;        [:flow-default] - the flow-content set;');
console.log(';;        [:explicit [children...]] - a fixed model (:\\%TEXT marks where text is allowed);');
console.log(';;        [:transparent [own-additions...]] - inherits the parent model plus these.');
console.log(`(def ^:private elements*\n{\n${rows.join('\n')}\n})`);
console.log(`(def ^:private phrasing-content*\n  ${set(phrasing)})`);
console.log(`(def ^:private flow-content*\n  ${set(flow)})`);
console.log('(def ^:private prohibited*\n  {"a" #{"a" "button"}\n   "button" #{"a" "button"}\n   "form" #{"form"}})');
