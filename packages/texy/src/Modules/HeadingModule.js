/**
 * Processes heading syntax: underlined and surrounded (port of
 * Texy\Modules\HeadingModule). Balances the levels by the order of the
 * heading styles in the document (a Dynamic balancing) and hoists the
 * {toc: ...} labels; the top-level shift and the ID generation are the
 * HeadingPass transform, which runs after HTML sanitizing.
 */

import { Modifier } from "../Modifier.js";
import { HeadingNode, HeadingType } from "../nodes.js";
import { HeadingPass, collectHeadings } from "../Passes/HeadingPass.js";
import { ModifierHAlign } from "../Patterns.js";
import { Syntax } from "../Syntax.js";
import { Module } from "./Module.js";

export class HeadingModule extends Module {
  constructor(texy) {
    super();
    this.texy = texy;

    /** level of top heading, 1..6 (used by the transform pass) */
    this.top = 1;

    /** surrounded headings: more #### means higher heading */
    this.moreMeansHigher = true;

    /** balancing mode: HeadingModule.Dynamic | HeadingModule.Fixed */
    this.balancing = HeadingModule.Dynamic;

    /** @type {Object<string, number>} underline character => level 1..6 */
    this.levels = { "#": 1, "*": 2, "=": 3, "-": 4 };

    /** generate ID for headings? (transform pass) */
    this.generateID = false;

    /** prefix for autogenerated IDs */
    this.idPrefix = "toc-";

    texy.addPass(doc => this.processHeadings(doc));
  }

  beforeParse() {
    this.texy.addBlockSyntax(
      Syntax.HeadingUnderlined,
      String.raw`~^
				( \S .{0,1000} )                 # heading text (1)
				` +
        ModifierHAlign +
        String.raw`? # modifier (2)
				\n
				( \#{3,}+ | \*{3,}+ | ={3,}+ | -{3,}+ )  # underline characters (3)
			$~mUx`,
      (context, matches, offsets) => this.parseUnderline(context, matches, offsets),
    );

    this.texy.addBlockSyntax(
      Syntax.HeadingSurrounded,
      String.raw`~^
				( \#{2,}+ | ={2,}+ )             # opening characters (1)
				(.+)                             # heading text (2)
				` +
        ModifierHAlign +
        String.raw`? # modifier (2)
			$~mUx`,
      (context, matches, offsets) => this.parseSurround(context, matches, offsets),
    );
  }

  /** The level as written, by the notation alone. */
  readLevel(marker, type) {
    if (type === HeadingType.Underlined) {
      return this.levels[marker[0]];
    }

    const length = Math.min(7, Math.max(2, marker.length));
    return this.moreMeansHigher ? 8 - length : length - 1;
  }

  /**
   * Runs the heading transform pass: balances the levels the Dynamic way
   * and hoists the {toc: ...} label out of the modifier.
   * @param {import('../nodes.js').DocumentNode} doc
   */
  processHeadings(doc) {
    const headings = collectHeadings(doc);
    if (this.balancing === HeadingModule.Dynamic) {
      this.balanceLevels(headings);
    }

    for (const node of headings) {
      const hoisted = HeadingPass.hoistOverride(node);
      node.titleOverride ??= hoisted; // a pass that ran earlier may have set its own
    }
  }

  /**
   * Levels are read from the notation, the level of a node may have been
   * changed or cut off.
   * @param {HeadingNode[]} headings
   */
  balanceLevels(headings) {
    const underlined = new Map(); // level => level, keyed sorted ascending
    let top = Number.MAX_SAFE_INTEGER;
    for (const node of headings) {
      if (node.marker !== null) {
        const level = this.readLevel(node.marker, node.type);
        if (node.type === HeadingType.Underlined) {
          underlined.set(level, level);
        } else {
          top = Math.min(top, level);
        }
      }
    }

    // rank (0-based) of every used underlined level, ascending
    const order = new Map(
      [...underlined.values()].sort((a, b) => a - b).map((level, rank) => [level, rank]),
    );

    for (const node of headings) {
      if (node.marker !== null) {
        const level = this.readLevel(node.marker, node.type);
        node.level = Math.min(
          6,
          node.type === HeadingType.Surrounded ? level - top + 1 : order.get(level) + 1,
        );
      }
    }
  }

  /**
   * Parses underlined heading.
   */
  parseUnderline(context, matches, offsets) {
    const [, mContent, mMod, mLine] = matches;
    const level = this.readLevel(mLine, HeadingType.Underlined);
    const contentOffset = offsets[1];
    return new HeadingNode(
      context.parseInline(mContent.trim(), contentOffset),
      level,
      HeadingType.Underlined,
      Modifier.parse(mMod, offsets[2] ?? null),
      { offset: offsets[0], length: matches[0].length },
      mLine[0],
      { offset: contentOffset, length: mContent.trimEnd().length },
    );
  }

  /**
   * Parses surrounded heading.
   */
  parseSurround(context, matches, offsets) {
    let [, mLine, mContent, mMod] = matches;
    const level = this.readLevel(mLine, HeadingType.Surrounded);
    mContent = mContent.replace(new RegExp("[" + mLine[0].replace(/[#=]/g, String.raw`\$&`) + " ]+$"), "");
    let contentOffset = offsets[2];

    // Adjust offset for leading whitespace removed by trim
    const trimmed = mContent.replace(/^[ \t\n\r\u0000\u000B]+/, "");
    const leadingSpaces = mContent.length - trimmed.length;
    contentOffset += leadingSpaces;

    return new HeadingNode(
      context.parseInline(mContent.trim(), contentOffset),
      level,
      HeadingType.Surrounded,
      Modifier.parse(mMod, offsets[3] ?? null),
      { offset: offsets[0], length: matches[0].length },
      mLine,
      { offset: contentOffset, length: trimmed.length },
    );
  }
}

HeadingModule.Dynamic = 1; // auto-leveling
HeadingModule.Fixed = 2; // fixed-leveling
